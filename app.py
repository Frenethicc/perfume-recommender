# ------------------------------
# Configuration
# ------------------------------
BASE_DIR = Path(__file__).resolve().parent
TOP_K = 5
DEFAULT_MIN_RATING = 4.0
DEFAULT_MIN_REVIEWS = 350

SYNONYM_MAP = {
    "orange blossom": "orange_blossom",
    "sea salt": "sea_salt",
    "oud wood": "oud",
    "vanille": "vanilla",
    "oudh": "oud",
    "patchouly": "patchouli",
    "musk": "musky",
}
SYNONYM_PATTERNS = [
    (re.compile(r"(?<!\w)" + re.escape(source) + r"(?!\w)"), target)
    for source, target in sorted(SYNONYM_MAP.items(), key=lambda item: len(item[0]), reverse=True)
]

DESIGNER_BRANDS = [
    "Dior", "Chanel", "Yves Saint Laurent", "Givenchy",
    "Giorgio Armani", "Gucci", "Prada", "Versace",
    "Dolce & Gabbana", "Calvin Klein", "Burberry",
    "Hermes", "Bvlgari"
]
NICHE_BRANDS = [
    "Parfums de Marly", "Maison Francis Kurkdjian", "Byredo", "Diptyque",
    "Amouage", "Xerjoff", "Creed", "Initio Parfums Prives", "Le Labo",
    "Kilian", "Frederic Malle", "Mancera", "Montale", "Nishane"
]
MIDDLE_EAST_BRANDS = [
    "Lattafa", "Armaf", "Rasasi", "Ajmal", "Al Haramain", "Swiss Arabian",
    "Afnan", "Nabeel", "Arabian Oud", "Khadlaj"
]
BRAND_GROUPS = {
    "designer": DESIGNER_BRANDS,
    "niche": NICHE_BRANDS,
    "middle_east": MIDDLE_EAST_BRANDS,
}


def normalize_text(value):
    """Keep this identical to the normalization function in the notebook."""
    text = "" if pd.isna(value) else str(value)
    text = text.lower()
    text = re.sub(r"[^a-z0-9\s_]", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    for pattern, replacement in SYNONYM_PATTERNS:
        text = pattern.sub(replacement, text)
    return re.sub(r"\s+", " ", text).strip()


def deduplicate_tokens(text):
    return " ".join(dict.fromkeys(str(text).split()))


# Alias untuk variasi nama yang memang merujuk pada brand yang sama di dataset.
BRAND_ALIASES = {
    "lattafa perfumes": "lattafa",
    "al haramain perfumes": "al haramain",
    "by kilian": "kilian",
    "bulgari": "bvlgari",
}


def normalize_brand_name(value):
    """Menyeragamkan huruf, aksen, tanda baca, dan spasi pada nama brand."""
    text = "" if pd.isna(value) else str(value)
    text = unicodedata.normalize("NFKD", text)
    text = "".join(char for char in text if not unicodedata.combining(char))
    text = text.lower().replace("&", " ")
    text = re.sub(r"[^a-z0-9]+", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return BRAND_ALIASES.get(text, text)


NORMALIZED_BRAND_GROUPS = {
    category: {normalize_brand_name(name) for name in names}
    for category, names in BRAND_GROUPS.items()
}


def brand_category_mask(brand_series, brand_type):
    """Mencocokkan nama brand yang sudah dinormalisasi secara utuh, bukan substring."""
    if brand_type is None:
        return pd.Series(True, index=brand_series.index)
    if brand_type not in BRAND_GROUPS:
        raise ValueError(f"brand_type must be one of {list(BRAND_GROUPS)} or None")
    normalized = brand_series.map(normalize_brand_name)
    return normalized.isin(NORMALIZED_BRAND_GROUPS[brand_type])


@st.cache_resource(show_spinner=False)
def load_assets():
    """Load model artifacts once per Streamlit process."""
    required = ["tfidf.pkl", "tfidf_matrix.pkl", "data.pkl"]
    missing = [name for name in required if not (BASE_DIR / name).exists()]
    if missing:
        raise FileNotFoundError(
            "Artefak belum tersedia: " + ", ".join(missing)
            + ". Jalankan notebook refactored dan letakkan artefak di folder yang sama dengan app.py."
        )
    with open(BASE_DIR / "tfidf.pkl", "rb") as file:
        tfidf = pickle.load(file)
    with open(BASE_DIR / "tfidf_matrix.pkl", "rb") as file:
        tfidf_matrix = pickle.load(file)
    df = pd.read_pickle(BASE_DIR / "data.pkl")
    if len(df) != tfidf_matrix.shape[0]:
        raise ValueError("Jumlah baris data.pkl tidak sama dengan jumlah baris matriks TF-IDF.")
    return tfidf, tfidf_matrix, df


def recommend_perfume(
    user_input,
    df,
    tfidf,
    tfidf_matrix,
    weather=None,
    min_rating=DEFAULT_MIN_RATING,
    min_reviews=DEFAULT_MIN_REVIEWS,
    brand_type=None,
    top_n=TOP_K,
):
    """Apply the same query normalization, similarity calculation, and filters as the notebook."""
    if not isinstance(user_input, str) or not user_input.strip():
        raise ValueError("Masukkan setidaknya satu kata kunci aroma.")

    normalized_query = deduplicate_tokens(normalize_text(user_input))
    user_vector = tfidf.transform([normalized_query])
    if user_vector.nnz == 0:
        raise ValueError(
            "Kata kunci tidak ditemukan dalam kosakata model. Coba istilah notes lain, misalnya vanilla, woody, fresh, atau citrus."
        )

    scores = cosine_similarity(user_vector, tfidf_matrix).ravel()
    if len(scores) != len(df):
        raise ValueError("Jumlah skor kemiripan tidak sama dengan jumlah baris dataset.")

    candidates = df.copy()
    candidates["score"] = scores

    # Keep behavior consistent with the notebook: choose the exact weather category.
    if weather is not None:
        candidates = candidates.loc[candidates["weather_suitability"].eq(weather)]

    candidates = candidates.loc[
        candidates["Rating Value"].ge(min_rating).fillna(False)
        & candidates["Rating Count"].ge(min_reviews).fillna(False)
    ]

    if brand_type is not None:
        candidates = candidates.loc[brand_category_mask(candidates["Brand"], brand_type)]

    columns = [
        "Perfume", "Brand", "Rating Value", "Rating Count", "weather_suitability",
        "score", "Top", "Middle", "Base", "main_accords", "combined_clean", "url"
    ]
    columns = [column for column in columns if column in candidates.columns]
    return candidates.sort_values("score", ascending=False).head(top_n)[columns].reset_index(drop=True)


